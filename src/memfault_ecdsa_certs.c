int memfault_install_ecdsa_certs(void) {
  int rv = tls_credential_add(GTS_ROOT_R4_SEC_TAG, TLS_CREDENTIAL_CA_CERTIFICATE,
                              s_gts_root_r4_der, sizeof(s_gts_root_r4_der));
  if (rv == -EEXIST) {
    return 0;
  }
  if (rv != 0) {
    MEMFAULT_LOG_ERROR("Failed to install GTS Root R4 cert (sec_tag=%d): %d",
                       GTS_ROOT_R4_SEC_TAG, rv);
  }
  return rv;
}
